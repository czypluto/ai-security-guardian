# ==================== CLI ====================

def main():
    parser = argparse.ArgumentParser(
        description='🎨 二次元角色转换器 - PNG → ESP32 C Header',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
使用示例:
  # 单表情转换
  python image_to_character.py -i happy.png -n my_chibi -e happy -o ./output/

  # 批量转换
  python image_to_character.py --batch expressions.json -o ./output/

  # 生成示例配置
  python image_to_character.py --example-config expressions.json

  # OLED模式 (默认 40x48)
  python image_to_character.py -i idle.png -n chibi -e idle --mode mono --size 40x48

  # TFT彩屏模式 (64x64 RGB565)
  python image_to_character.py -i idle.png -n chibi -e idle --mode rgb565 --size 64x64
        """
    )

    parser.add_argument('--input', '-i', help='输入图片路径')
    parser.add_argument('--name', '-n', default='custom_chibi', help='角色名称')
    parser.add_argument('--expression', '-e', default='idle',
                       choices=['idle','happy','working','worried','angry','sleep','love','greeting'],
                       help='表情名称')
    parser.add_argument('--output', '-o', default='./output/', help='输出目录')
    parser.add_argument('--mode', '-m', default='mono',
                       choices=['mono','rgb565'], help='颜色模式')
    parser.add_argument('--size', '-s', default='40x48', help='尺寸 WxH')
    parser.add_argument('--threshold', '-t', type=int, default=128, help='二值化阈值 (0-255)')
    parser.add_argument('--invert', action='store_true', help='反转颜色')
    parser.add_argument('--preview', '-p', action='store_true', help='终端预览')
    parser.add_argument('--batch', '-b', help='批量转换 (JSON配置)')
    parser.add_argument('--example-config', help='生成示例配置文件')

    args = parser.parse_args()

    # 生成示例配置
    if args.example_config:
        generate_example_config(args.example_config)
        return

    # 批量模式
    if args.batch:
        batch_convert(args.batch, args.output)
        return

    # 单图模式
    if not args.input:
        parser.print_help()
        print("\n❌ 需要 --input 或 --batch 参数")
        sys.exit(1)

    if not os.path.exists(args.input):
        print(f"❌ 文件不存在: {args.input}")
        sys.exit(1)

    # 解析尺寸
    w, h = map(int, args.size.split('x'))

    print(f"🔄 处理: {args.input}")
    print(f"   角色: {args.name}, 表情: {args.expression}")
    print(f"   模式: {args.mode}, 尺寸: {w}x{h}")

    if args.mode == 'rgb565':
        bitmap, w_out, h_out = image_to_rgb565_bitmap(args.input, w, h)
    else:
        bitmap, w_out, h_out = image_to_monochrome_bitmap(
            args.input, w, h, args.threshold, args.invert
        )

    print(f"   位图大小: {len(bitmap)} bytes ({w_out}x{h_out})")

    if args.preview and args.mode == 'mono':
        preview_bitmap(bitmap, w_out, h_out)

    # 生成 header
    output_path = os.path.join(args.output, f'{args.name}.h')
    generate_header(args.name, {args.expression: bitmap},
                    w_out, h_out, args.mode, output_path)

    print(f"\n🎉 完成!")


if __name__ == '__main__':
    main()
